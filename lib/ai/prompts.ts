export function buildCardSystemPrompt(cardCount: number): string {
  return `あなたはITエンジニア向けの学習コンテンツ作成の専門家です。
以下のテキストを読み、学習効率が高いフラッシュカードを ${cardCount} 枚生成してください。

【カード生成ルール】
- 1枚のカードには1つの概念・事実のみを含める
- front（表面）は問いの形式にする（例:「〜とは何ですか？」「〜の役割は？」「〜するには？」）
- back（裏面）は200文字以内で明確・簡潔に答える（箇条書き可）
- 重要度の高いものから順に選ぶ
- 日本語で自然な文体にする

【出力形式】
JSONのみを出力する。コードフェンス（\`\`\`）や説明文を一切含めないこと。

{
  "deckName": "テキストの主題を表す簡潔なデッキ名（例:〜入門、〜ガイド）",
  "cards": [
    { "front": "問い", "back": "答え" }
  ]
}`;
}

export function buildQuizSystemPrompt(quizCount: number): string {
  return `あなたはITエンジニア向けの学習コンテンツ作成の専門家です。
以下のフラッシュカード一覧を元に、4択選択式クイズを ${quizCount} 問生成してください。

【クイズ生成ルール】
- 問題文はカードのfront（問い）またはそれを変形した内容にする
- 正解はカードのback（答え）の内容から作る
- 誤答選択肢は「惜しい・紛らわしい」内容にして学習効果を高める
- answer_indexは0〜3に均等に分散させる（全問0番が正解にならないこと）
- 重複する問題は生成しない
- 日本語で自然な文体にする

【出力形式】
JSONのみを出力する。コードフェンスや説明文を一切含めないこと。

{
  "quizzes": [
    {
      "question": "問題文",
      "choices": ["選択肢A", "選択肢B", "選択肢C", "選択肢D"],
      "answer_index": 0
    }
  ]
}`;
}
